package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const referenceHeader = "<!-- Generated by `mise run docs:gen` from the commands' help text. Do not edit by hand. -->\n\n"

// WriteCommandReference writes one Markdown page per visible command of root into dir, plus a
// README.md index, from the same text --help shows. The root's Long is skipped: it is the terminal
// banner.
func WriteCommandReference(root *cobra.Command, dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	cmds := visibleCommands(root)
	for _, c := range cmds {
		path := filepath.Join(dir, pageName(c))
		if err := os.WriteFile(path, []byte(commandPage(c, root)), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	index := filepath.Join(dir, "README.md")
	if err := os.WriteFile(index, []byte(commandIndex(root, cmds)), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", index, err)
	}
	return nil
}

func visibleCommands(c *cobra.Command) []*cobra.Command {
	out := []*cobra.Command{c}
	for _, sub := range c.Commands() {
		if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
			continue
		}
		out = append(out, visibleCommands(sub)...)
	}
	return out
}

func pageName(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "_") + ".md"
}

func commandLink(c *cobra.Command) string {
	return fmt.Sprintf("[%s](%s): %s", c.CommandPath(), pageName(c), prose(c.Short))
}

// prose escapes help text for a Markdown page outside code: a placeholder such as <dir> would
// otherwise be read as an HTML tag and vanish.
func prose(s string) string {
	return strings.NewReplacer("<", `\<`, ">", `\>`).Replace(s)
}

func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || strings.HasSuffix(s, ".") {
		return s
	}
	return s + "."
}

func commandPage(c, root *cobra.Command) string {
	var b strings.Builder
	b.WriteString(referenceHeader)
	fmt.Fprintf(&b, "# %s\n\n%s\n", c.CommandPath(), prose(sentence(c.Short)))
	if c != root && strings.TrimSpace(c.Long) != "" {
		fmt.Fprintf(&b, "\n%s\n", prose(strings.TrimSpace(c.Long)))
	}

	usage := c.CommandPath() + " [command]"
	if c.Runnable() {
		usage = c.UseLine()
	}
	fmt.Fprintf(&b, "\n## Usage\n\n```text\n%s\n```\n", usage)

	if ex := strings.TrimSpace(c.Example); ex != "" {
		lines := strings.Split(c.Example, "\n")
		for i, l := range lines {
			lines[i] = strings.TrimPrefix(l, "  ")
		}
		fmt.Fprintf(&b, "\n## Examples\n\n```bash\n%s\n```\n", strings.TrimSpace(strings.Join(lines, "\n")))
	}

	writeFlagTable(&b, "Flags", c.NonInheritedFlags())
	writeFlagTable(&b, "Global flags", c.InheritedFlags())

	var subs []string
	for _, sub := range c.Commands() {
		if !sub.Hidden && sub.Name() != "help" && sub.Name() != "completion" {
			subs = append(subs, "- "+commandLink(sub))
		}
	}
	if len(subs) > 0 {
		fmt.Fprintf(&b, "\n## Subcommands\n\n%s\n", strings.Join(subs, "\n"))
	}

	b.WriteString("\n## See also\n\n")
	if c.HasParent() {
		fmt.Fprintf(&b, "- %s\n", commandLink(c.Parent()))
	}
	b.WriteString("- [All commands](README.md)\n")
	b.WriteString("- [Exit codes](../exit-codes.md)\n")
	b.WriteString("- [Environment variables](../environment-variables.md)\n")
	return b.String()
}

func writeFlagTable(b *strings.Builder, title string, fs *pflag.FlagSet) {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", flagCell(f), defaultCell(f), prose(strings.ReplaceAll(f.Usage, "|", `\|`))))
	})
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(b, "\n## %s\n\n| Flag | Default | Description |\n|---|---|---|\n%s\n", title, strings.Join(rows, "\n"))
}

func flagCell(f *pflag.Flag) string {
	name := "`--" + f.Name
	switch t := f.Value.Type(); t {
	case "bool":
	case "stringSlice", "stringArray":
		name += " <strings>"
	default:
		name += " <" + t + ">"
	}
	name += "`"
	if f.Shorthand != "" {
		name = "`-" + f.Shorthand + "`, " + name
	}
	return name
}

func defaultCell(f *pflag.Flag) string {
	switch f.DefValue {
	case "", "false", "[]", "0":
		return ""
	}
	return "`" + f.DefValue + "`"
}

func commandIndex(root *cobra.Command, cmds []*cobra.Command) string {
	var b strings.Builder
	b.WriteString(referenceHeader)
	fmt.Fprintf(&b, "# Commands\n\nEvery %s command, from the same text as `%s <command> --help`.\n\n", root.Name(), root.Name())
	for _, c := range cmds {
		indent := strings.Repeat("  ", len(strings.Fields(c.CommandPath()))-1)
		fmt.Fprintf(&b, "%s- %s\n", indent, commandLink(c))
	}
	b.WriteString("\nSee also [Exit codes](../exit-codes.md) and [Environment variables](../environment-variables.md).\n")
	return b.String()
}
